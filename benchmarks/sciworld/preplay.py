"""
Pre-play mechanism for workflow-level planning.

Before the agent acts on a new task, a lightweight LLM call traverses
the workflow graph and selects an ordered sequence of workflows — analogous
to hippocampal pre-play of candidate paths before navigation.

The resulting plan is injected into the system prompt in place of the raw
workflow file dump used by vanilla AWM.
"""
from __future__ import annotations

import re
from pathlib import Path
from typing import List, Optional

from workflow_graph import WorkflowGraph


_INSTRUCTION = (Path(__file__).parent / "prompt" / "preplay_instruction.txt").read_text().strip()
_ONE_SHOT    = (Path(__file__).parent / "prompt" / "preplay_one_shot.txt").read_text().strip()
_SYSTEM_MSG  = _INSTRUCTION + "\n\n" + _ONE_SHOT


def run_preplay(
    llm_chat_fn,        # callable(messages) -> str
    goal: str,
    site: str,
    graph: WorkflowGraph,
    current_obs: str = "",
    completed_workflows: List[str] = None,
    use_reliability: bool = True,
    workflow_content: dict = None,
    task_embedding=None,
    failed_experiences: List[str] = None,
) -> tuple:
    """
    Run a single LLM call to pre-play a workflow sequence for the task.
    Returns (workflow_names: List[str], plan_text: str).

    workflow_names: ordered list of workflow names (top-level plan entries only),
    used for graph edge recording and plan_ids resolution.

    plan_text: the full structured plan as generated by the LLM (workflow names +
    task-specific sub-steps), used for injection into the agent's system prompt.

    workflow_content: optional dict mapping workflow name (lowercase) → step text.
    When provided, the full workflow steps are included in the preplay context so
    the LLM can judge relevance from actual content, not just the workflow name.

    use_reliability=False: ablation mode — workflow list and ordering are kept
    but edge reliability scores are hidden from the LLM (trans_section blank).
    """
    nodes = graph.get_nodes_for_site(site)
    if not nodes:
        return [], ""

    user_msg = _build_user_msg(
        goal, site, graph, nodes,
        current_obs=current_obs,
        completed_workflows=completed_workflows or [],
        use_reliability=use_reliability,
        workflow_content=workflow_content,
        task_embedding=task_embedding,
        failed_experiences=failed_experiences or [],
    )
    messages = [
        {"role": "system", "content": _SYSTEM_MSG},
        {"role": "user",   "content": user_msg},
    ]
    response = llm_chat_fn(messages)
    return _parse_plan(response)


def format_plan_for_injection(
    plan: List[str],
    plan_text: str = None,
    workflow_content: dict = None,
) -> str:
    """
    Format the pre-played plan for injection into the agent's system prompt.

    plan_text: if provided, inject the LLM-generated structured plan directly
    (workflow names + task-specific sub-steps). This is preferred over
    reconstructing from generic workflow_content.

    workflow_content: fallback when plan_text is absent — injects generic
    workflow steps under each plan entry.
    """
    if not plan:
        return ""

    header = (
        "Suggested workflow plan for this task (from past experience):\n"
        "Follow these steps as a guide; adjust based on what you observe."
    )

    if plan_text:
        return f"{header}\n\n{plan_text.strip()}"

    # Fallback: reconstruct from workflow names + generic content
    lines = [header]
    for i, wf_name in enumerate(plan):
        name_key = wf_name.strip().lower()
        lines.append(f"\nStep {i + 1}: {wf_name}")
        if workflow_content:
            steps = workflow_content.get(name_key)
            if steps:
                for step_line in steps.strip().splitlines():
                    lines.append(f"  {step_line}")

    return "\n".join(lines)


def record_execution(
    plan: List[str],
    graph: WorkflowGraph,
    site: str,
    reward: float,
    plan_ids: Optional[List[str]] = None,
    task_embedding=None,
) -> None:
    """
    After a task completes, record the planned transition sequence in the graph.
    Edge reliability is updated proportionally to the episode reward (clipped to [0,1]).

    plan_ids: node_id for each plan entry, resolved at preplay time before any
    _sync_graph renames. When provided, transitions are recorded by stable node_id
    rather than by name, avoiding misses after induction renames nodes mid-episode.

    task_embedding: unit-normalized list of floats for the current task. When
    provided, each edge accumulates a reward-weighted sum of task embeddings so
    that get_task_reliability() can return task-specific scores at query time.
    """
    if len(plan) < 2:
        return

    if plan_ids and len(plan_ids) == len(plan):
        # Fast path: use pre-resolved node IDs (name-change-safe).
        for i in range(len(plan_ids) - 1):
            src_id = plan_ids[i]
            tgt_id = plan_ids[i + 1]
            if src_id and tgt_id and src_id in graph.nodes and tgt_id in graph.nodes:
                graph.record_transition(
                    src_id, tgt_id, score=reward, task_embedding=task_embedding
                )
        return

    # Fallback: look up by current node name (works when graph hasn't been resynced).
    nodes_by_name = {n.name.lower().strip(): n for n in graph.get_nodes_for_site(site)}
    for i in range(len(plan) - 1):
        src = nodes_by_name.get(_plan_name(plan[i]))
        tgt = nodes_by_name.get(_plan_name(plan[i + 1]))
        if src and tgt:
            graph.record_transition(
                src.node_id, tgt.node_id, score=reward, task_embedding=task_embedding
            )


# ── Internal helpers ──────────────────────────────────────────────────────────

def _build_user_msg(
    goal, site, graph, nodes,
    current_obs: str = "",
    completed_workflows: List[str] = None,
    use_reliability: bool = True,
    workflow_content: dict = None,
    task_embedding=None,
    failed_experiences: List[str] = None,
) -> str:
    # Workflow list — include full steps when available so the LLM can judge
    # relevance from actual content rather than just the workflow name.
    wf_lines = []
    for node in nodes:
        wf_lines.append(f"### {node.name}")
        if workflow_content:
            steps = workflow_content.get(node.name.lower().strip())
            if steps:
                wf_lines.append(steps.strip())
        wf_lines.append("")
    wf_section = "\n".join(wf_lines).strip() or "(no workflows available yet)"

    # Transitions sorted by reliability descending (hidden in ablation mode).
    # When task_embedding is available, use task-specific reliability (cosine
    # similarity to the reward-weighted centroid of past task embeddings).
    # Falls back to global reliability when no embedding data exists for an edge.
    if use_reliability:
        def _score(edge):
            if task_embedding is not None:
                return graph.get_task_reliability(edge, task_embedding)
            return edge.reliability

        scored = [(edge, _score(edge)) for edge in graph.edges.values()]
        scored.sort(key=lambda x: (x[1], x[0].count), reverse=True)
        trans_lines = []
        for edge, score in scored:
            src = graph.nodes.get(edge.source_id)
            tgt = graph.nodes.get(edge.target_id)
            if not (src and tgt and src.site == site):
                continue
            trans_lines.append(
                f"- '{src.name}' → '{tgt.name}' "
                f"(relevance: {score:.2f}, {edge.count} trials)"
            )
        trans_section = "\n".join(trans_lines) or "(no prior transitions recorded)"
    else:
        trans_section = "(reliability scores hidden — ablation mode)"

    # Replanning context (used when called mid-episode)
    if completed_workflows or current_obs:
        parts = []
        if completed_workflows:
            done_list = "\n".join(f"  ✓ {w}" for w in completed_workflows)
            parts.append(f"Steps Already Completed This Episode\n{done_list}")
        if current_obs:
            parts.append(f"Current Environment Observation\n{current_obs.strip()[:600]}")
        context_block = "\n\n".join(parts)
        footer = (
            f"\n\n{context_block}\n\n"
            "Using the above context, generate a plan for the REMAINING steps. "
            "Follow known sequences where they apply, and add or modify steps "
            "based on your understanding of the current situation."
        )
    else:
        footer = (
            "\n\nGenerate a plan for this task. Use the workflow graph as evidence — "
            "follow known sequences where they apply, and add or modify steps "
            "based on your understanding of the task."
        )

    # Past episode summaries that contained failed steps.
    # Full summaries are shown so the LLM has complete context; the Failed steps
    # lines (marked [x]) are the most actionable signal — prioritise them when
    # deciding what NOT to include in the plan.
    if failed_experiences:
        fail_lines = "\n\n".join(failed_experiences)
        fail_section = (
            f"\nPast Episode Experiences\n"
            f"Each entry below contains a 'Failed steps' line. Read the full action sequence carefully "
            f"to understand why the episode did not fully succeed. Identify the root cause of failure, "
            f"then design your plan for the current task to reason around that cause.\n"
            f"{fail_lines}"
        )
    else:
        fail_section = ""

    return f"""\
Task Goal
{goal}

Available Workflows
{wf_section}

Known Workflow Transitions (from past experience)
Sorted by relevance to this task (higher = this sequence worked well on similar tasks).
{trans_section}{fail_section}{footer}

<plan>
"""


def _plan_name(entry: str) -> str:
    return entry.strip().lower()


def _parse_plan(response: str) -> tuple:
    """
    Extract plan from a <plan>...</plan> block.
    Returns (names, plan_text) where:
      names     — top-level workflow names only (numbered entries, no sub-steps)
      plan_text — full plan text as written by the LLM (for agent injection)
    """
    plan_match = re.search(r'<plan>(.*?)(?:</plan>|$)', response, re.DOTALL)
    if not plan_match:
        return [], ""
    plan_text = plan_match.group(1)

    names = []
    for line in plan_text.splitlines():
        # Only top-level numbered entries: "1. Name" or "1) Name"
        m = re.match(r'^\d+[.)]\s+(.+)', line)
        if m:
            names.append(m.group(1).strip())
    return names, plan_text.strip()
